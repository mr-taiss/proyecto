export function normalizarNombre(nombre: string): string {
  return nombre
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .replace(/\s+/g, " ")
    .toUpperCase();
}

export function encontrarNombreAutorizado(nombre: string): string | null {
  const nombreNormalizado = normalizarNombre(nombre);

  return (
    nombresAutorizados.find(
      (nombreAutorizado) => normalizarNombre(nombreAutorizado) === nombreNormalizado
    ) ?? null
  );
}
